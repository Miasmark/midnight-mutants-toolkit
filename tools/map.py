#!/usr/bin/env python3
"""
Per-page memory map for the cart: how much of each 256-byte page the tracer
reached as code, plus a content guess for everything it did not reach.

The guess is deliberately crude -- it exists to point a human at the pages worth
looking at next, not to be believed on its own.

Usage:  python map.py <rom.a78> [-c annotations.json] [-o MEMORY_MAP.md]
"""
import argparse
import os
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import m6502
from disasm import Cart, Config, Analyzer, BANK_SIZE

# opcodes that dominate real 6502 game code
COMMON = bytes([0xA9, 0xA5, 0xA6, 0xA4, 0x85, 0x86, 0x84, 0x8D, 0x8E, 0x8C,
                0xAD, 0xAE, 0xAC, 0x20, 0x4C, 0x60, 0xD0, 0xF0, 0x10, 0x30,
                0x90, 0xB0, 0xC9, 0xBD, 0x9D, 0xB9, 0x99, 0xB1, 0x91, 0xE8,
                0xCA, 0xC8, 0x88, 0xAA, 0xA8, 0x98, 0x8A, 0x48, 0x68, 0x18,
                0x38, 0x29, 0x09, 0x49, 0x69, 0xE9, 0xE6, 0xC6, 0xEE, 0xCE])


def classify(page, traced):
    c = Counter(page)
    if c[0x00] >= 250:
        return "empty ($00 fill)"
    if c[0xFF] >= 250:
        return "empty ($FF fill)"
    if traced > 0.02:
        return ""
    common = sum(c[b] for b in COMMON) / len(page)
    illegal = sum(1 for b in page if m6502.OPCODES[b][2]) / len(page)
    # 160x2 / 320 bitmap data is dominated by a handful of nibble-pair values
    nibbly = sum(c[b] for b in (0x00, 0x55, 0xAA, 0xFF, 0x54, 0x15, 0x51, 0x45,
                                0x11, 0x44, 0x05, 0x50, 0x40, 0x10, 0x01)) / len(page)
    if common > 0.20 and illegal < 0.28:
        return "CODE? (untraced)"
    if nibbly > 0.45:
        return "graphics (160x2-ish)"
    if common > 0.13 and illegal < 0.35:
        return "code or dense data"
    return "data"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("rom")
    ap.add_argument("-c", "--config", default=None)
    ap.add_argument("-o", "--out", default="MEMORY_MAP.md")
    args = ap.parse_args()

    cart = Cart(args.rom)
    cfg = Config(args.config)
    an = Analyzer(cart, cfg)
    for b in cfg.blocks:
        from disasm import parse_loc
        s, a = parse_loc(b["loc"])
        e = parse_loc(b["end"])[1] if "end" in b else a + b.get("len", 1)
        for x in range(a, e):
            an.forced_data.add((s, x))

    last = cart.rom[cart.fixed_hi * BANK_SIZE:]
    vec = {n: last[o] | (last[o + 1] << 8) for n, o in
           (("NMI", 0x3FFA), ("RESET", 0x3FFC), ("IRQ", 0x3FFE))}
    entries = [(cart.space_of(v, None), v, None) for v in vec.values()
               if cart.space_of(v, None)]
    from disasm import parse_loc
    entries += [(s, a, None) for (s, a) in cfg.entries]
    an.run(entries)
    for _ in range(8):
        new = []
        for tgt, site in an.scan_ram_vectors(0x2135, 0x2136):
            sp = cart.space_of(tgt, None)
            if sp and not an.code.intersection({(sp, tgt)}):
                new.append((sp, tgt, None))
        if not new:
            break
        an.run(new)

    covered = {}
    for (s, a) in an.code:
        n = an.insn[(s, a)][3]
        for i in range(n):
            covered.setdefault(s, set()).add(a + i)

    spaces = [("f6", "bank 6 @ $4000 (fixed)"), ("f7", "bank 7 @ $C000 (fixed)")] + \
             [("b%d" % i, "bank %d @ $8000 (paged)" % i) for i in range(cart.nbanks)
              if i not in (cart.fixed_lo, cart.fixed_hi)]

    out = ["# Midnight Mutants (NTSC, 1990) -- cartridge memory map", "",
           "Generated by `tools/map.py`.  \"traced\" is the share of the page the",
           "recursive-descent tracer proved to be code; everything else is a guess",
           "from byte statistics and should be confirmed by eye.", "",
           "| vector | value |", "|---|---|"]
    for n, v in vec.items():
        out.append("| %s | $%04X |" % (n, v))
    out.append("")

    for space, title in spaces:
        cov = covered.get(space, set())
        base = cart.base_of(space)
        out += ["## %s -- ROM bank %d, %s" % (space, cart.bank_of(space), title),
                "", "file offset $%05X-$%05X" %
                (128 + cart.bank_of(space) * BANK_SIZE,
                 128 + (cart.bank_of(space) + 1) * BANK_SIZE - 1), "",
                "| page | traced as code | content |", "|---|---|---|"]
        run = []
        for p in range(BANK_SIZE // 256):
            a0 = base + p * 256
            page = cart.slice(space, a0, 256)
            t = sum(1 for i in range(256) if a0 + i in cov) / 256
            run.append((a0, t, classify(page, t)))
        # collapse identical consecutive rows
        i = 0
        while i < len(run):
            j = i
            while (j + 1 < len(run) and run[j + 1][2] == run[i][2]
                   and abs(run[j + 1][1] - run[i][1]) < 0.02
                   and (run[i][2] != "" or run[i][1] == 0)):
                j += 1
            a0, t, k = run[i]
            a1 = run[j][0] + 255
            tavg = sum(r[1] for r in run[i:j + 1]) / (j - i + 1)
            out.append("| $%04X-$%04X | %.0f%% | %s |" % (a0, a1, tavg * 100,
                                                          k or "code"))
            i = j + 1
        out.append("")

    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", args.out)


if __name__ == "__main__":
    main()
